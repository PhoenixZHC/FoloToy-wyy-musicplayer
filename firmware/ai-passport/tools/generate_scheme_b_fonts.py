#!/usr/bin/env python3
"""Rasterize installed OFL Noto CJK SC fonts into flash-resident LVGL 2bpp fonts.

Requires Pillow with FreeType. No network, converter package or server changes.
Usage: python3 tools/generate_scheme_b_fonts.py [--full]
"""
import argparse
import ctypes
import ctypes.util
import hashlib
import json
import unicodedata
from functools import lru_cache
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "main/fonts"
SANS = Path("/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc")
SERIF = Path("/usr/share/fonts/opentype/noto/NotoSerifCJK-Regular.ttc")
NUMBERS = Path("/usr/share/fonts/opentype/urw-base35/NimbusRoman-Regular.otf")
LINE_METRICS = {8:(10,2),9:(12,3),10:(13,3),12:(16,4),13:(16,4),
                14:(17,4),17:(21,5),18:(21,5),22:(26,6),25:(29,7)}
MAX_BITMAP_BYTES = 1 << 20

def gb2312():
    result = set()
    for lead in range(0xB0, 0xF8):
        for trail in range(0xA1, 0xFF):
            try: result.update(bytes([lead, trail]).decode("gb2312"))
            except UnicodeDecodeError: pass
    return result

def han(ch):
    return 0x3400 <= ord(ch) <= 0x9FFF or 0xF900 <= ord(ch) <= 0xFAFF

SIMPLIFIED_NAME_ADDITIONS = set("祎喆祐珺昀晞灏堃淏烜玟玥垚燚翊翎")

@lru_cache(maxsize=None)
def source_codepoints(source, index):
    """Use the real FreeType cmap rather than rasterizing missing-glyph boxes."""
    library_name = ctypes.util.find_library("freetype")
    if not library_name:
        raise RuntimeError("FreeType shared library is required to verify glyph coverage")
    ft = ctypes.CDLL(library_name)
    ft.FT_Init_FreeType.argtypes = [ctypes.POINTER(ctypes.c_void_p)]
    ft.FT_New_Face.argtypes = [ctypes.c_void_p, ctypes.c_char_p, ctypes.c_long, ctypes.POINTER(ctypes.c_void_p)]
    ft.FT_Get_First_Char.argtypes = [ctypes.c_void_p, ctypes.POINTER(ctypes.c_uint)]
    ft.FT_Get_First_Char.restype = ctypes.c_ulong
    ft.FT_Get_Next_Char.argtypes = [ctypes.c_void_p, ctypes.c_ulong, ctypes.POINTER(ctypes.c_uint)]
    ft.FT_Get_Next_Char.restype = ctypes.c_ulong
    ft.FT_Done_Face.argtypes = [ctypes.c_void_p]
    ft.FT_Done_FreeType.argtypes = [ctypes.c_void_p]
    library, face = ctypes.c_void_p(), ctypes.c_void_p()
    if ft.FT_Init_FreeType(ctypes.byref(library)):
        raise RuntimeError("Cannot initialize FreeType")
    try:
        if ft.FT_New_Face(library, str(source).encode(), index, ctypes.byref(face)):
            raise RuntimeError("Cannot open font: " + str(source))
        glyph = ctypes.c_uint()
        cp = ft.FT_Get_First_Char(face, ctypes.byref(glyph))
        result = set()
        while glyph.value:
            result.add(cp)
            cp = ft.FT_Get_Next_Char(face, cp, ctypes.byref(glyph))
        return result
    finally:
        if face.value:
            ft.FT_Done_Face(face)
        ft.FT_Done_FreeType(library)

def expanded_characters(required):
    supported = source_codepoints(SANS, 2) & source_codepoints(SERIF, 2)
    # Full simplified-Chinese standard plus explicit name characters and ASCII English.
    base = required | gb2312() | SIMPLIFIED_NAME_ADDITIONS | set(map(chr, range(32, 127)))
    missing = sorted(ord(ch) for ch in base if ord(ch) not in supported)
    if missing:
        raise ValueError("Required source glyphs missing: " + ", ".join("U+%04X" % cp for cp in missing))
    return base

def write_server_charset(characters, path):
    ordered = "".join(sorted(ch for ch in characters if ord(ch) > 0x7F))
    path.write_text(
        "// Generated by firmware/ai-passport/tools/generate_scheme_b_fonts.py.\n"
        "// Do not edit this file by hand.\n"
        "export const DEVICE_SUPPORTED_TEXT = " + json.dumps(ordered, ensure_ascii=False) + ";\n",
        encoding="utf-8")

def rle_encode(values):
    """LVGL fmt_txt repeated-pixel encoding, checked against its decoder states."""
    bits=[]
    def put(v,n): bits.extend((v>>i)&1 for i in range(n-1,-1,-1))
    pos=0;previous=None;repeated=False
    while pos<len(values):
        value=values[pos]
        if not repeated:
            put(value,2);pos+=1
            repeated=previous==value and pos>1;previous=value
            continue
        run=0
        while pos+run<len(values) and values[pos+run]==previous:run+=1
        if run<11:
            for _ in range(run):put(1,1)
            pos+=run
            if pos<len(values):put(0,1);put(values[pos],2);previous=values[pos];pos+=1
            repeated=False
        else:
            for _ in range(11):put(1,1)
            extra=min(63,run-10);put(extra,6)
            pos+=10+extra
            if pos<len(values):put(values[pos],2);previous=values[pos];pos+=1
            repeated=False
    bits.extend([0]*16)
    return bytes(sum(bits[i+j]<<(7-j) for j in range(8)) for i in range(0,len(bits)-7,8))

def rle_decode(data,count):
    bit=0;state=0;previous=0;repeat=0;out=[]
    def get(n):
        nonlocal bit
        value=0
        for _ in range(n):value=(value<<1)|((data[bit//8]>>(7-bit%8))&1);bit+=1
        return value
    for _ in range(count):
        if state==0:
            value=get(2)
            if bit!=2 and previous==value:repeat=0;state=1
            previous=value
        elif state==1:
            v=get(1);repeat+=1;value=previous
            if v:
                if repeat==11:
                    repeat=get(6)
                    if repeat:state=2
                    else:value=get(2);previous=value;state=0
            else:value=get(2);previous=value;state=0
        else:
            repeat-=1;value=previous
            if repeat==0:value=get(2);previous=value;state=0
        out.append(value)
    return out

def generate(name, size, source, chars, index=2):
    font = ImageFont.truetype(str(source), size=size, index=index)
    codepoints = sorted(set(map(ord, chars)))
    missing = set(codepoints) - source_codepoints(source, index)
    if missing:
        raise ValueError("Missing source glyphs in %s: %s" % (name, sorted(missing)))
    boxes = [font.getbbox(chr(cp), anchor="ls") for cp in codepoints]
    line_height, descent = LINE_METRICS.get(size, (max(-b[1] for b in boxes) + max(b[3] for b in boxes), max(b[3] for b in boxes)))
    ascent = line_height - descent
    chunks = []
    data, glyphs, points = bytearray(), ["{0}"], []
    fitted = 0
    for cp in codepoints:
        ch = chr(cp)
        x0,y0,x1,y1 = font.getbbox(ch, anchor="ls")
        w,h = x1-x0,y1-y0
        img=Image.new("L",(max(w,1),max(h,1)))
        if w and h: ImageDraw.Draw(img).text((-x0,-y0),ch,font=font,fill=255,anchor="ls")
        if h and (y0 < -ascent or y1 > descent):
            y0, y1 = max(y0, -ascent), min(y1, descent)
            h = y1 - y0
            if h <= 0:
                raise ValueError("Glyph does not fit line: " + ch)
            img = img.resize((max(w,1),h),Image.Resampling.LANCZOS)
            fitted += 1
        values=[min(3,(value+42)//85) for value in img.getdata()] if w and h else []
        filtered=[value ^ (values[i-w] if i>=w else 0) for i,value in enumerate(values)]
        encoded=rle_encode(filtered)
        if rle_decode(encoded,len(filtered))!=filtered:raise ValueError("RLE round-trip failed: "+ch)
        if len(encoded) > MAX_BITMAP_BYTES:
            raise ValueError("Glyph exceeds LVGL bitmap limit")
        if len(data) + len(encoded) > MAX_BITMAP_BYTES:
            chunks.append((data,glyphs,points))
            data, glyphs, points = bytearray(), ["{0}"], []
        offset=len(data)
        data.extend(encoded)
        points.append(cp)
        glyphs.append("{.bitmap_index=%d,.adv_w=%d,.box_w=%d,.box_h=%d,.ofs_x=%d,.ofs_y=%d}" % (offset,round(font.getlength(ch)*16),w,h,x0,-y1))
    chunks.append((data,glyphs,points))
    text = '#include "lvgl.h"\n#include "src/font/fmt_txt/lv_font_fmt_txt.h"\n/* Generated from %s; see font-licenses/ for source license. Do not edit. */\n' % source.name
    for part in reversed(range(len(chunks))):
        data,glyphs,points = chunks[part]
        bitmap=",\n".join(",".join("0x%02x" % b for b in data[i:i+24]) for i in range(0,len(data),24))
        offsets=",".join(str(cp-points[0]) for cp in points)
        text += "static const uint8_t bitmap_%d[]={\n%s\n};\n" % (part,bitmap)
        text += "static const lv_font_fmt_txt_glyph_dsc_t glyphs_%d[]={\n%s\n};\n" % (part,",\n".join(glyphs))
        text += "static const uint16_t unicode_list_%d[]={%s};\n" % (part,offsets)
        text += "static const lv_font_fmt_txt_cmap_t cmaps_%d[]={{.range_start=%d,.range_length=%d,.glyph_id_start=1,.unicode_list=unicode_list_%d,.list_length=%d,.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}};\n" % (part,points[0],points[-1]-points[0]+1,part,len(points))
        text += "static lv_font_fmt_txt_dsc_t dsc_%d={.glyph_bitmap=bitmap_%d,.glyph_dsc=glyphs_%d,.cmaps=cmaps_%d,.cmap_num=1,.bpp=2,.bitmap_format=LV_FONT_FMT_TXT_COMPRESSED};\n" % (part,part,part,part)
        symbol = name if part == 0 else name + "_part_%d" % part
        fallback = "NULL" if part == len(chunks)-1 else "&" + name + "_part_%d" % (part+1)
        text += "%sconst lv_font_t %s={.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height=%d,.base_line=%d,.dsc=&dsc_%d,.fallback=%s};\n" % ("" if part==0 else "static ",symbol,line_height,descent,part,fallback)
    (FONT_DIR/(name+".c")).write_text(text,encoding="utf-8")
    return dict(name=name,size=size,glyphs=len(codepoints),han_glyphs=sum(han(chr(cp)) for cp in codepoints),latin_glyphs=sum("LATIN" in unicodedata.name(chr(cp), "") for cp in codepoints),bitmap_bytes=sum(len(c[0]) for c in chunks),bitmap_parts=len(chunks),max_part_bytes=max(len(c[0]) for c in chunks),fitted_glyphs=fitted,line_height=line_height,source=source.name,source_sha256=hashlib.sha256(source.read_bytes()).hexdigest())

def main():
    parser=argparse.ArgumentParser();parser.add_argument("--full",action="store_true")
    args=parser.parse_args()
    fixed=set(chr(cp) for cp in range(32,127))
    for path in (ROOT/"main").glob("*.c"):
        fixed.update(ch for ch in path.read_text() if ord(ch)>127 and ord(ch)<65536)
    fixed.update("–×—−…·，。？！（）暂停返回播放音量亮度确认取消歌曲网络账号显示日夜余白章节我的歌单")
    dynamic=expanded_characters(fixed) if args.full else fixed
    # Preserve ASCII English and actual UI punctuation in fixed UI sizes too.
    fixed |= {ch for ch in dynamic if not han(ch)}
    result=[]
    for size in (8,9,10,12,13,14,17,18,22,24,43,46):
        chars=dynamic if size in (9,10,12,14,24) else fixed
        if size==43:chars=set("0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz.- …你好已扫码。")
        if size==46:chars=set("余白")
        result.append(generate("netease_ui_font_%d"%size,25 if size==24 else size,SERIF if size in (17,22,24,43,46) else SANS,chars))
    for size in (60,80):result.append(generate("netease_ui_font_%d"%size,size,NUMBERS,"0123456789%",0))
    (FONT_DIR/"scheme_b_font_manifest.json").write_text(json.dumps(result,ensure_ascii=False,indent=2)+"\n")
    write_server_charset(dynamic, ROOT.parent.parent / "server/src/generated/deviceCharset.ts")
    print(json.dumps(result,ensure_ascii=False,indent=2))
if __name__=="__main__":main()
