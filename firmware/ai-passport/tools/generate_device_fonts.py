#!/usr/bin/env python3
"""Generate the metadata fonts and the server character allowlist together."""

from __future__ import annotations

import json
import os
import re
import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
PROJECT_ROOT = ROOT.parent.parent
FONT_DIR = ROOT / "main" / "fonts"
SERVER_CHARSET_PATH = PROJECT_ROOT / "server" / "src" / "generated" / "deviceCharset.ts"
FONT_SOURCE = Path(os.environ.get("NETEASE_FONT_SOURCE", r"C:\Windows\Fonts\simhei.ttf"))
FONT_CONVERTER_VERSION = "1.5.3"
FONT_CONVERTER = PROJECT_ROOT / "server" / "node_modules" / "lv_font_conv" / "lv_font_conv.js"
DYNAMIC_FONT_SIZES = (10, 14, 18, 24)
STATIC_REFERENCE_SIZE = 12


def read_sparse_font_characters(path: Path) -> set[str]:
    source = path.read_text(encoding="utf-8")
    unicode_lists = {
        name: [int(value, 16) for value in re.findall(r"0x([0-9a-f]+)", body, re.I)]
        for name, body in re.findall(
            r"static const uint16_t (unicode_list_\d+)\[\] = \{(.*?)\};",
            source,
            re.DOTALL,
        )
    }
    cmap_matches = re.findall(
        r"\{\s*\.range_start = (\d+), \.range_length = (\d+),.*?"
        r"\.unicode_list = (NULL|unicode_list_\d+),.*?\.list_length = (\d+), "
        r"\.type = (LV_FONT_FMT_TXT_CMAP_[A-Z0-9_]+)\s*\}",
        source,
        re.DOTALL,
    )
    if not cmap_matches:
        raise RuntimeError(f"cannot read font character maps from {path}")

    characters: set[str] = set()
    for range_start_text, range_length_text, list_name, list_length_text, cmap_type in cmap_matches:
        range_start = int(range_start_text)
        range_length = int(range_length_text)
        if list_name == "NULL":
            codepoints = range(range_start, range_start + range_length)
        else:
            offsets = unicode_lists.get(list_name)
            expected_count = int(list_length_text)
            if offsets is None or len(offsets) != expected_count:
                raise RuntimeError(f"{path}: invalid {list_name} for {cmap_type}")
            codepoints = (range_start + offset for offset in offsets)
        characters.update(chr(codepoint) for codepoint in codepoints if codepoint > 0x7F)
    return characters


def gb2312_level_one_characters() -> set[str]:
    characters: set[str] = set()
    for lead in range(0xB0, 0xD8):
        for trail in range(0xA1, 0xFF):
            try:
                characters.add(bytes((lead, trail)).decode("gb2312"))
            except UnicodeDecodeError:
                continue
    return characters


def build_dynamic_characters() -> str:
    existing_characters = read_sparse_font_characters(
        FONT_DIR / f"netease_ui_font_{STATIC_REFERENCE_SIZE}.c"
    )
    characters = existing_characters | gb2312_level_one_characters()
    return "".join(sorted(characters, key=ord))


def codepoint_range_arguments(characters: str) -> list[str]:
    codepoints = sorted({ord(character) for character in characters})
    ranges: list[str] = []
    start = codepoints[0]
    end = start
    for codepoint in codepoints[1:]:
        if codepoint == end + 1:
            end = codepoint
            continue
        ranges.append(f"0x{start:X}" if start == end else f"0x{start:X}-0x{end:X}")
        start = end = codepoint
    ranges.append(f"0x{start:X}" if start == end else f"0x{start:X}-0x{end:X}")

    arguments: list[str] = []
    chunk = ""
    for value in ranges:
        candidate = value if not chunk else f"{chunk},{value}"
        if len(candidate) > 1000:
            arguments.extend(("-r", chunk))
            chunk = value
        else:
            chunk = candidate
    if chunk:
        arguments.extend(("-r", chunk))
    return arguments


def generate_font(size: int, characters: str) -> Path:
    output = FONT_DIR / f"netease_ui_font_{size}.c"
    command = [
        "node",
        str(FONT_CONVERTER),
        "--font",
        str(FONT_SOURCE),
        "-r",
        "0x20-0x7F",
        *codepoint_range_arguments(characters),
        "--size",
        str(size),
        "--bpp",
        "2",
        "--format",
        "lvgl",
        "--lv-include",
        "lvgl.h",
        "--lv-font-name",
        f"netease_ui_font_{size}",
        "--output",
        str(output),
        "--force-fast-kern-format",
    ]
    subprocess.run(command, cwd=ROOT, check=True)
    return output


def write_server_charset(characters: set[str]) -> None:
    SERVER_CHARSET_PATH.parent.mkdir(parents=True, exist_ok=True)
    ordered = "".join(sorted(characters, key=ord))
    encoded = json.dumps(ordered, ensure_ascii=False)
    content = (
        "// Generated by firmware/ai-passport/tools/generate_device_fonts.py.\n"
        "// Do not edit this file by hand.\n"
        f"export const DEVICE_SUPPORTED_TEXT = {encoded};\n"
    )
    SERVER_CHARSET_PATH.write_text(content, encoding="utf-8", newline="\n")


def main() -> int:
    if not FONT_SOURCE.is_file():
        raise SystemExit(
            f"Font source not found: {FONT_SOURCE}. Set NETEASE_FONT_SOURCE to a compatible CJK font."
        )
    if not FONT_CONVERTER.is_file():
        raise SystemExit(
            "Font converter is missing. Run npm install in the server directory first "
            f"(required version: {FONT_CONVERTER_VERSION})."
        )

    requested_characters = build_dynamic_characters()
    generated_sets: list[set[str]] = []
    for size in DYNAMIC_FONT_SIZES:
        output = generate_font(size, requested_characters)
        generated_sets.append(read_sparse_font_characters(output))
        print(f"Generated {output.relative_to(ROOT)}")

    reference = generated_sets[0]
    if any(characters != reference for characters in generated_sets[1:]):
        raise SystemExit("Generated dynamic fonts do not contain the same characters")
    if len(reference) < 3000:
        raise SystemExit(f"Generated font only contains {len(reference)} dynamic characters")

    write_server_charset(reference)
    print(f"Generated server allowlist with {len(reference)} characters")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
